package cooldown

import (
	"bytes"
	"crypto/sha256"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/obentoo/bentoolkit/internal/common/fileutil"
)

// ErrChangedSinceLoad is wrapped by Save when profiles/package.mask no longer
// holds the bytes the block was loaded from.
var ErrChangedSinceLoad = errors.New("changed since the cooldown block was loaded")

const unmaskHeader = "# Generated by bentoolkit from the cooldown block of profiles/package.mask.\n" +
	"# Never edit by hand. Link it once to unmask the versions under cooldown on this host:\n" +
	"#   ln -s /var/db/repos/bentoo/.autoupdate/cooldown.unmask /etc/portage/package.unmask/bentoo-cooldown\n"

// Save writes the block back into overlayRoot's profiles/package.mask, then
// re-derives .autoupdate/cooldown.unmask from it. Both files are replaced
// through fileutil.WriteFileAtomic, and every byte of package.mask outside
// the block is kept exactly.
//
// Save refuses, wrapping ErrChangedSinceLoad, when package.mask changed since
// Load (or the previous Save); a Block that was never loaded cannot be saved.
// The mask is written first: it is the fail-safe side, and a failed unmask
// write is repaired by the next successful Save.
//
// Callers own the lock: Save holds none, so the read, the splice and the
// write must run inside the caller's apply lock.
func (b *Block) Save(overlayRoot string) error {
	maskPath := filepath.Join(overlayRoot, MaskRel)
	if !b.hashed {
		return fmt.Errorf("saving the cooldown block of %s: the block was not loaded from it", maskPath)
	}
	if b.Days < 1 || b.Days > MaxDays {
		return fmt.Errorf("saving the cooldown block of %s: days=%d outside 1..%d", maskPath, b.Days, MaxDays)
	}
	for _, e := range b.Entries {
		if err := validateEntry(e); err != nil {
			return fmt.Errorf("saving the cooldown block of %s: %w; nothing written", maskPath, err)
		}
	}
	data, err := os.ReadFile(maskPath) // #nosec G304 -- the overlay's own profiles/package.mask
	if err != nil {
		return fmt.Errorf("re-reading %s: %w", maskPath, err)
	}
	if sha256.Sum256(data) != b.loadHash {
		return fmt.Errorf("%s: %w; reload and retry", maskPath, ErrChangedSinceLoad)
	}
	_, sp, err := parse(maskPath, data)
	if err != nil {
		return err
	}
	info, err := os.Stat(maskPath)
	if err != nil {
		return fmt.Errorf("reading the mode of %s: %w", maskPath, err)
	}

	var out bytes.Buffer
	out.Write(data[:sp.start])
	out.WriteString(b.render())
	out.Write(data[sp.stop:])
	if err := fileutil.WriteFileAtomic(maskPath, out.Bytes(), info.Mode().Perm()); err != nil {
		return fmt.Errorf("saving the cooldown block: %w", err)
	}
	b.loadHash = sha256.Sum256(out.Bytes())

	unmaskPath := filepath.Join(overlayRoot, UnmaskRel)
	if err := os.MkdirAll(filepath.Dir(unmaskPath), 0o755); err != nil { // #nosec G301 -- the overlay's .autoupdate directory, world-readable like the tree
		return fmt.Errorf("creating the directory of %s: %w", unmaskPath, err)
	}
	if err := fileutil.WriteFileAtomic(unmaskPath, []byte(b.unmaskList()), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", unmaskPath, err)
	}
	return nil
}

// unmaskList renders the package.unmask list: the header, then one atom per
// entry.
func (b *Block) unmaskList() string {
	var sb strings.Builder
	sb.WriteString(unmaskHeader)
	for _, e := range b.Entries {
		sb.WriteString(e.Atom() + "\n")
	}
	return sb.String()
}
