const (
	s090SourceBytes  = "SOURCE-ARCHIVE govulncheck"
	s090PinnedBytes  = "PINNED-TARBALL govulncheck"
	s090TarballBytes = "FAKE-VENDOR-TARBALL generated by the fake tar"
	s090Uploader     = "fake-upload"
)

type s090ExecCall struct {
	name string
	args []string
	cmd  *exec.Cmd
}

type s090PkgdevView struct {
	distdir string
	vendor  []byte // nil when the vendor file was absent at the call
}

// s090Exec stands in for egencache, tar, go, pkgdev and the upload program.
// Side effects happen when the command is built, which is before it runs.
type s090Exec struct {
	mu            sync.Mutex
	calls         []s090ExecCall
	stagedRoot    string
	md5Rel        string
	md5           string
	vendorFile    string
	egencacheFail bool
	goFail        bool
	pkgdevFail    bool
	uploadFail    bool
	regenModules  string
	pinnedModules string
	lastTop       string
	pkgdev        []s090PkgdevView
	onUpload      func(args []string)
}

func s090TarArgs(args []string) (create, extract bool, file, dir string) {
	for i := 0; i < len(args); i++ {
		a := args[i]
		next := func() string {
			if i+1 < len(args) {
				i++
				return args[i]
			}
			return ""
		}
		switch {
		case a == "--create":
			create = true
		case a == "--extract" || a == "--get":
			extract = true
		case a == "--file":
			file = next()
		case strings.HasPrefix(a, "--file="):
			file = strings.TrimPrefix(a, "--file=")
		case a == "-C" || a == "--directory":
			dir = next()
		case strings.HasPrefix(a, "--directory="):
			dir = strings.TrimPrefix(a, "--directory=")
		case strings.HasPrefix(a, "--"):
		case strings.HasPrefix(a, "-") || (i == 0 && a != ""):
			cluster := strings.TrimPrefix(a, "-")
			for j := 0; j < len(cluster); j++ {
				switch cluster[j] {
				case 'c':
					create = true
				case 'x':
					extract = true
				case 'C':
					dir = next()
				case 'f':
					if j == len(cluster)-1 {
						file = next()
					} else {
						file = cluster[j+1:]
						j = len(cluster)
					}
				}
			}
		}
	}
	return create, extract, file, dir
}

func (e *s090Exec) fn(ctx context.Context, name string, arg ...string) *exec.Cmd {
	ok := true
	e.mu.Lock()
	defer e.mu.Unlock()
	switch name {
	case "egencache":
		ok = !e.egencacheFail
		if ok && e.md5 != "" {
			if _, err := os.Stat(e.stagedRoot); err == nil {
				p := filepath.Join(e.stagedRoot, "metadata", "md5-cache", e.md5Rel)
				_ = os.MkdirAll(filepath.Dir(p), 0o755)
				_ = os.WriteFile(p, []byte(e.md5), 0o644)
			}
		}
	case "tar":
		create, extract, file, dir := s090TarArgs(arg)
		switch {
		case create && file != "":
			_ = os.MkdirAll(filepath.Dir(file), 0o755)
			_ = os.WriteFile(file, []byte(s090TarballBytes), 0o644)
		case extract && file != "" && dir != "":
			data, _ := os.ReadFile(file)
			switch {
			case bytes.HasPrefix(data, []byte("SOURCE")):
				e.lastTop = filepath.Join(dir, "vuln-1.9.0")
				_ = os.MkdirAll(e.lastTop, 0o755)
				_ = os.WriteFile(filepath.Join(e.lastTop, "go.mod"), []byte("module golang.org/x/vuln\n\ngo 1.21\n"), 0o644)
			case bytes.HasPrefix(data, []byte("PINNED")):
				p := filepath.Join(dir, "vuln-1.8.0", "vendor", "modules.txt")
				_ = os.MkdirAll(filepath.Dir(p), 0o755)
				_ = os.WriteFile(p, []byte(e.pinnedModules), 0o644)
			default:
				ok = false
			}
		}
	case "go":
		ok = !e.goFail
		if ok && e.lastTop != "" {
			p := filepath.Join(e.lastTop, "vendor", "modules.txt")
			_ = os.MkdirAll(filepath.Dir(p), 0o755)
			_ = os.WriteFile(p, []byte(e.regenModules), 0o644)
		}
	case "pkgdev":
		ok = !e.pkgdevFail
		view := s090PkgdevView{}
		for i, a := range arg {
			if a == "--distdir" && i+1 < len(arg) {
				view.distdir = arg[i+1]
			}
		}
		if data, err := os.ReadFile(filepath.Join(view.distdir, e.vendorFile)); err == nil {
			view.vendor = data
		}
		e.pkgdev = append(e.pkgdev, view)
	case s090Uploader:
		ok = !e.uploadFail
		if e.onUpload != nil {
			e.onUpload(arg)
		}
	}
	child := "true"
	if !ok {
		child = "false"
	}
	cmd := exec.CommandContext(ctx, child)
	e.calls = append(e.calls, s090ExecCall{name: name, args: slices.Clone(arg), cmd: cmd})
	return cmd
}

func (e *s090Exec) named(name string) []s090ExecCall {
	e.mu.Lock()
	defer e.mu.Unlock()
	var out []s090ExecCall
	for _, c := range e.calls {
		if c.name == name {
			out = append(out, c)
		}
	}
	return out
}

// ---- log sink -------------------------------------------------------------

type s090Record struct {
	level slog.Level
	text  string // message and every attribute value
}

type s090Sink struct {
	mu   sync.Mutex
	recs []s090Record
}

type s090Handler struct {
	sink  *s090Sink
	attrs []slog.Attr
}

func (h s090Handler) Enabled(context.Context, slog.Level) bool { return true }
func (h s090Handler) Handle(_ context.Context, r slog.Record) error {
	var b strings.Builder
	b.WriteString(r.Message)
	for _, a := range h.attrs {
		fmt.Fprintf(&b, " %s=%v", a.Key, a.Value)
	}
	r.Attrs(func(a slog.Attr) bool {
		fmt.Fprintf(&b, " %s=%v", a.Key, a.Value)
		return true
	})
	h.sink.mu.Lock()
	h.sink.recs = append(h.sink.recs, s090Record{r.Level, b.String()})
	h.sink.mu.Unlock()
	return nil
}
func (h s090Handler) WithAttrs(as []slog.Attr) slog.Handler {
	return s090Handler{h.sink, append(slices.Clone(h.attrs), as...)}
}
func (h s090Handler) WithGroup(string) slog.Handler { return h }
func (s *s090Sink) logger() *slog.Logger            { return slog.New(s090Handler{sink: s}) }

func (s *s090Sink) warned(parts ...string) bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	for _, r := range s.recs {
		if r.level != slog.LevelWarn {
			continue
		}
		all := true
		for _, p := range parts {
			all = all && strings.Contains(r.text, p)
		}
		if all {
			return true
		}
	}
	return false
}

