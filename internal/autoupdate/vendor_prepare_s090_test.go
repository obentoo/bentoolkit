// ---- fake HTTP ------------------------------------------------------------

type s090Resp struct {
	status int
	body   string
	err    error
}

type s090Request struct{ method, url string }

// s090Transport answers from a table keyed "METHOD URL"; anything else is a
// 404. It records every request so a test can prove none was made.
type s090Transport struct {
	mu     sync.Mutex
	routes map[string]func() s090Resp
	seen   []s090Request
}

func (tr *s090Transport) set(method, url string, r s090Resp) {
	tr.mu.Lock()
	defer tr.mu.Unlock()
	if tr.routes == nil {
		tr.routes = map[string]func() s090Resp{}
	}
	tr.routes[method+" "+url] = func() s090Resp { return r }
}

func (tr *s090Transport) setFunc(method, url string, fn func() s090Resp) {
	tr.mu.Lock()
	defer tr.mu.Unlock()
	if tr.routes == nil {
		tr.routes = map[string]func() s090Resp{}
	}
	tr.routes[method+" "+url] = fn
}

func (tr *s090Transport) RoundTrip(req *http.Request) (*http.Response, error) {
	tr.mu.Lock()
	tr.seen = append(tr.seen, s090Request{req.Method, req.URL.String()})
	fn := tr.routes[req.Method+" "+req.URL.String()]
	tr.mu.Unlock()
	r := s090Resp{status: http.StatusNotFound}
	if fn != nil {
		r = fn()
	}
	if r.err != nil {
		return nil, r.err
	}
	return &http.Response{
		StatusCode: r.status, Status: http.StatusText(r.status), Request: req,
		Header: http.Header{}, Body: io.NopCloser(strings.NewReader(r.body)), ContentLength: int64(len(r.body)),
	}, nil
}

func (tr *s090Transport) requests() []s090Request {
	tr.mu.Lock()
	defer tr.mu.Unlock()
	return slices.Clone(tr.seen)
}

func s090Client(tr *s090Transport) *fetch.RetryableHTTPClient {
	c := fetch.NewRetryableHTTPClient().WithCircuitBreaker(false)
	c.SetHTTPClient(&http.Client{Transport: tr})
	c.SetDelayFunc(func(time.Duration) {})
	return c
}

