func (f *s090Fix) applier(t *testing.T, fx *fakeFixer, opts ...ApplierOption) *Applier {
	t.Helper()
	s090Write(t, filepath.Join(f.overlay, s090Pkg, "govulncheck-1.8.0.ebuild"), f.body)
	s090Write(t, filepath.Join(f.overlay, "profiles", "repo_name"), "bentoo\n")
	s090Write(t, filepath.Join(f.overlay, "metadata", "layout.conf"), "masters = gentoo\n")
	s090Write(t, filepath.Join(f.overlay, s090Pkg, "Manifest"),
		"DIST govulncheck-1.8.0.tar.gz 10 BLAKE2B aa SHA512 bb\nDIST govulncheck-1.8.0-vendor.tar.xz 10 BLAKE2B cc SHA512 dd\n")
	base := []ApplierOption{
		WithExecCommand(f.exec.fn),
		WithApplierHTTPClient(s090Client(f.tr)),
		WithApplierReporter(f.rec),
		WithApplierLogger(f.sink.logger()),
		WithConfirmFunc(func(string) bool { return true }),
		WithApplierDistdir(f.host, ""),
		WithApplierDistfilesCache(f.cache),
	}
	if fx != nil {
		base = append(base, WithApplierFixer(fx))
	}
	a, err := NewApplier(f.overlay, filepath.Join(t.TempDir(), "config"), append(base, opts...)...)
	if err != nil {
		t.Fatalf("NewApplier: %v", err)
	}
	return a
}

