func s090EnvValue(env []string, key string) string {
	val := os.Getenv(key)
	for _, kv := range env {
		if v, ok := strings.CutPrefix(kv, key+"="); ok {
			val = v
		}
	}
	return val
}

func s090AssertEmptyDir(t *testing.T, dir, what string) {
	t.Helper()
	left, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("reading %s: %v", what, err)
	}
	if len(left) != 0 {
		t.Errorf("%s still holds %v after the vendor step", what, left)
	}
}

