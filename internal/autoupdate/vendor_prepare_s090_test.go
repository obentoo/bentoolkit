// R2.4, R3.1, R3.2: the manifest step digests the generated tarball from the
// staged distdir, without the fixer, and hands that distdir to the gates.
func TestStagedManifestDigestsTheGeneratedTarball(t *testing.T) {
	f := s090Fixture(t, "1.9.0", "go-module", s090VendorOK)
	f.tr.set(http.MethodHead, s090VendorOK, s090Resp{status: 404})
	fx := &fakeFixer{summary: "should not run"}
	a := f.applier(t, fx)

	distdir, err := a.runManifestWithFix(t.Context(), f.cand(), s090Pkg, "1.9.0", &ApplyResult{})
	t.Cleanup(func() { removeStagedDistdir(nil, distdir) })
	if err != nil {
		t.Fatalf("runManifestWithFix: %v", err)
	}
	if fx.called != 0 {
		t.Errorf("the LLM fixer ran %d time(s)", fx.called)
	}
	if len(f.exec.pkgdev) != 1 {
		t.Fatalf("pkgdev ran %d time(s), want 1", len(f.exec.pkgdev))
	}
	view := f.exec.pkgdev[0]
	if string(view.vendor) != s090TarballBytes {
		t.Errorf("pkgdev's --distdir %q held %q as the vendor file, want the generated tarball", view.distdir, view.vendor)
	}
	if view.distdir != distdir {
		t.Errorf("returned distdir %q, but pkgdev digested %q", distdir, view.distdir)
	}
}
