// R2.1, R2.4, R2.7, R2.8: a 404 on the vendor URI generates the tarball into
// the staged distdir, and the outcome carries every field its consumers read.
func TestPrepareVendorGeneratesOnA404(t *testing.T) {
	t.Setenv("GOFLAGS", "-mod=mod")
	f := s090Fixture(t, "1.9.0", "go-module", s090VendorOK)
	f.tr.set(http.MethodHead, s090VendorOK, s090Resp{status: 404})

	out, err := f.prepare(t)
	if err != nil {
		t.Fatalf("prepareVendorDistfile: %v", err)
	}
	if !out.Generated {
		t.Fatalf("outcome %+v: Generated is false after a 404", out)
	}
	wantPath := filepath.Join(f.distdir, "govulncheck-1.9.0-vendor.tar.xz")
	if out.File != "govulncheck-1.9.0-vendor.tar.xz" || out.URI != s090VendorOK || out.Tarball != wantPath {
		t.Errorf("outcome File/URI/Tarball = %q / %q / %q, want %q / %q / %q",
			out.File, out.URI, out.Tarball, "govulncheck-1.9.0-vendor.tar.xz", s090VendorOK, wantPath)
	}
	data, err := os.ReadFile(wantPath)
	if err != nil {
		t.Fatalf("the tarball is not in the staged distdir: %v", err)
	}
	sum := sha512.Sum512(data)
	if out.SHA512 != hex.EncodeToString(sum[:]) {
		t.Errorf("outcome SHA512 = %q, want the digest of %s", out.SHA512, wantPath)
	}
	if !slices.Contains(f.tr.requests(), s090Request{http.MethodHead, s090VendorOK}) {
		t.Errorf("no HEAD probe of %s; requests: %v", s090VendorOK, f.tr.requests())
	}
	gos := f.exec.named("go")
	if len(gos) != 1 || !slices.Equal(gos[0].args, []string{"mod", "vendor"}) {
		t.Fatalf("go calls = %+v, want one `go mod vendor`", gos)
	}
	if gos[0].cmd.Dir != f.exec.lastTop {
		t.Errorf("go ran in %q, want the unpacked top directory %q", gos[0].cmd.Dir, f.exec.lastTop)
	}
	if rel, err := filepath.Rel(f.sandbox, gos[0].cmd.Dir); err != nil || strings.HasPrefix(rel, "..") {
		t.Errorf("go ran in %q, outside the sandbox root %q", gos[0].cmd.Dir, f.sandbox)
	}
	if v := s090EnvValue(gos[0].cmd.Env, "GOFLAGS"); v != "-modcacherw" {
		t.Errorf("GOFLAGS reaching go = %q, want -modcacherw", v)
	}
	if v := s090EnvValue(gos[0].cmd.Env, "GOTOOLCHAIN"); v != "local" {
		t.Errorf("GOTOOLCHAIN reaching go = %q, want local", v)
	}
	s090AssertEmptyDir(t, f.sandbox, "the sandbox root")
	if !slices.Contains(f.rec.snapshot(), "TaskStage:"+s090Pkg+":vendor") {
		t.Errorf("no TaskStage(%s, vendor); events: %v", s090Pkg, f.rec.snapshot())
	}
}

